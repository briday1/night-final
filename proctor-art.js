function mantleRibbon(place,route,index,time) {
  const points = route.map(([x,y,z],i) => {
    const flow = i/(route.length-1);
    const sway = reducedMotion ? 0 : flow*Math.sin(time*1.65-index*.83-i*.97);
    return [x+sway*.30,y+sway*.09,z+sway*.14];
  });
  const profile = [.34,.31,.26,.19,.105,.028];
  const edge = (side,scale,lift=0) => points.map(([x,y,z],i) => {
    const a = points[Math.max(0,i-1)], b = points[Math.min(i+1,points.length-1)];
    const length = Math.hypot(b[0]-a[0],b[1]-a[1]);
    const width = side*scale*profile[i]*(index>3 ? 1.14 : 1);
    return place([x-(b[1]-a[1])*width/length,y+(b[0]-a[0])*width/length,z+lift]);
  });
  const left = edge(-1,1), right = edge(1,1);
  const middle = edge(1,.06,.044);
  shape(index%2 ? '#365057' : '#2b454e',[...left,...right.toReversed()]);
  shape(index%2 ? '#58716e' : '#516b6a',[...left,...middle.toReversed()]);
  for (let i=1;i<points.length-1;i++) {
    const [x,y,z] = points[i];
    if ((index+i)%2 === 0) {
      const next = points[i+1];
      shape('#6f8680',[left[i],place([x,y,z+.057]),place(mixPoint(points[i],next,.39))]);
    }
  }
}
